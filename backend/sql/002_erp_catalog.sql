-- สถานะ: ยังไม่ได้รันกับฐานข้อมูลจริง
-- คำสั่งชุดเดียวกันนี้ถูกใส่ไว้ใน UNIT_MIGRATION_STATEMENTS ของ backend/main.py
-- แล้วด้วย จึงจะถูกรันอัตโนมัติเมื่อ restart stock_api ครั้งถัดไป
-- ไฟล์นี้มีไว้ให้รีวิว/รันมือกรณีไม่อยาก restart
--
-- ทุกคำสั่งเป็น idempotent (IF NOT EXISTS) รันซ้ำได้ ไม่ทำข้อมูลเดิมหาย
-- ไม่มีคำสั่งไหนแก้/ลบข้อมูลที่มีอยู่
-- ============================================================================

-- หมวดหมู่สินค้า: เดิมระบบไม่มีเลย ปล่อย NULL ได้ ค่อยทยอยกรอกจากหน้าแก้สินค้า
ALTER TABLE IF EXISTS products
    ADD COLUMN IF NOT EXISTS category VARCHAR(100);

-- แยกของใช้ซ้ำ (ต้องตามเก็บคืนจากไซต์) ออกจากของสิ้นเปลือง (ส่งแล้วจบ)
-- ตั้งค่าเริ่มต้น CONSUMABLE เพราะของเดิมส่วนใหญ่เป็นของสิ้นเปลือง
-- และ CSV export เดิมก็ fix ค่า kind เป็น CONSUMABLE อยู่แล้ว
ALTER TABLE IF EXISTS products
    ADD COLUMN IF NOT EXISTS item_kind VARCHAR(20) NOT NULL DEFAULT 'CONSUMABLE';

-- ธงบอกว่า customer แถวนี้คือ "ไซต์งาน" จริง
-- ตาราง customers ปัจจุบันปนทั้งไซต์งาน ออฟฟิศของบริษัทเอง และชื่อบุคคล
ALTER TABLE IF EXISTS customers
    ADD COLUMN IF NOT EXISTS is_site BOOLEAN NOT NULL DEFAULT false;

-- ดัชนีช่วย query ของ catalog (ไม่บังคับ แต่ช่วยเวลาข้อมูลโตขึ้น)
CREATE INDEX IF NOT EXISTS idx_products_updated_at ON products(updated_at);
CREATE INDEX IF NOT EXISTS idx_delivery_items_product ON delivery_items(product_id);
CREATE INDEX IF NOT EXISTS idx_return_items_product ON return_items(product_id);

