-- ----------------------------------------------------------------------------
-- ตรวจผลก่อน COMMIT
-- ----------------------------------------------------------------------------
SELECT COALESCE(category, '(ยังไม่จัดหมวด)') AS category,
       COUNT(*) AS n,
       COUNT(*) FILTER (WHERE item_kind = 'REUSABLE')   AS reusable,
       COUNT(*) FILTER (WHERE item_kind = 'CONSUMABLE') AS consumable
FROM products
GROUP BY category
ORDER BY n DESC;

